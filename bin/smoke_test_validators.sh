#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT_DIR="$(mktemp -d "${TMPDIR:-/tmp}/codex-validator-smoke.XXXXXX")"
LEAK_TXT="$OUT_DIR/leaky_cover_letter.txt"
STRUCTURED_COVER_TXT="$OUT_DIR/structured_cover_letter.txt"
BAD_RESUME="$OUT_DIR/thin_resume.xml"
ONE_JOB_RESUME="$OUT_DIR/one_job_resume.xml"
BAD_MATRIX="$OUT_DIR/bad_match_matrix.json"
COVER_LOG="$OUT_DIR/cover-validator.log"
STRUCTURED_COVER_LOG="$OUT_DIR/structured-cover-validator.log"
RESUME_LOG="$OUT_DIR/resume-validator.log"
ONE_JOB_LOG="$OUT_DIR/one-job-validator.log"
MATRIX_LOG="$OUT_DIR/matrix-validator.log"
COVER_GENERATOR_LOG="$OUT_DIR/cover-generator.log"
STRUCTURED_COVER_GENERATOR_LOG="$OUT_DIR/structured-cover-generator.log"
RESUME_GENERATOR_LOG="$OUT_DIR/resume-generator.log"
ONE_JOB_GENERATOR_LOG="$OUT_DIR/one-job-generator.log"

cat > "$LEAK_TXT" <<'TXT'
company: Example Company
role: Software Engineer

location: date: April 24, 2026 salutation: Dear Hiring Team, closing: Sincerely, signature: Example Candidate
TXT

if "$ROOT/bin/validate_cover_letter.sh" "$LEAK_TXT" >"$COVER_LOG" 2>&1; then
  echo "Expected cover letter metadata leakage validation to fail." >&2
  exit 1
fi

grep -q "metadata labels are not allowed" "$COVER_LOG"
grep -q "location:" "$COVER_LOG"

if "$ROOT/bin/run_cover_letter.sh" "$LEAK_TXT" "$OUT_DIR/leaky_cover_letter.pdf" >"$COVER_GENERATOR_LOG" 2>&1; then
  echo "Expected cover letter generation with metadata leakage to fail." >&2
  exit 1
fi

test ! -f "$OUT_DIR/leaky_cover_letter.pdf"
grep -q "metadata labels are not allowed" "$COVER_GENERATOR_LOG"

cat > "$STRUCTURED_COVER_TXT" <<'TXT'
Dear Hiring Team,

I am applying for the Software Engineer role because it matches my Python and computer vision experience.

Sincerely,
Example Candidate
TXT

if "$ROOT/bin/validate_cover_letter.sh" "$STRUCTURED_COVER_TXT" >"$STRUCTURED_COVER_LOG" 2>&1; then
  echo "Expected cover letter source with greeting/signature to fail." >&2
  exit 1
fi

grep -q "greeting is generated by the template" "$STRUCTURED_COVER_LOG"
grep -q "closing/signature is generated by the template" "$STRUCTURED_COVER_LOG"

if "$ROOT/bin/run_cover_letter.sh" "$STRUCTURED_COVER_TXT" "$OUT_DIR/structured_cover_letter.pdf" >"$STRUCTURED_COVER_GENERATOR_LOG" 2>&1; then
  echo "Expected cover letter generation with greeting/signature to fail." >&2
  exit 1
fi

test ! -f "$OUT_DIR/structured_cover_letter.pdf"
grep -q "greeting is generated by the template" "$STRUCTURED_COVER_GENERATOR_LOG"

cat > "$BAD_RESUME" <<'XML'
<?xml version="1.0" encoding="UTF-8"?>
<resume>
  <projects>
    <project>
      <title>Thin Project</title>
      <highlights>
        <bullet>One supported bullet.</bullet>
        <bullet>Second supported bullet.</bullet>
      </highlights>
    </project>
  </projects>
  <employment>
    <job>
      <company>Thin Company</company>
      <title>Software Intern</title>
      <responsibilities>
        <bullet>Only one supported bullet.</bullet>
      </responsibilities>
    </job>
  </employment>
</resume>
XML

if "$ROOT/bin/validate_resume.sh" "$BAD_RESUME" >"$RESUME_LOG" 2>&1; then
  echo "Expected thin resume entry validation to fail." >&2
  exit 1
fi

grep -q "Thin Project" "$RESUME_LOG"
grep -q "Software Intern, Thin Company" "$RESUME_LOG"

if "$ROOT/bin/run_resume.sh" "$BAD_RESUME" "$OUT_DIR/thin_resume.pdf" >"$RESUME_GENERATOR_LOG" 2>&1; then
  echo "Expected resume generation with thin entries to fail." >&2
  exit 1
fi

test ! -f "$OUT_DIR/thin_resume.pdf"
grep -q "Thin Project" "$RESUME_GENERATOR_LOG"

cat > "$ONE_JOB_RESUME" <<'XML'
<?xml version="1.0" encoding="UTF-8"?>
<resume>
  <projects>
    <project>
      <title>Complete Project</title>
      <highlights>
        <bullet>First supported bullet.</bullet>
        <bullet>Second supported bullet.</bullet>
        <bullet>Third supported bullet.</bullet>
      </highlights>
    </project>
  </projects>
  <employment>
    <job>
      <company>Only Company</company>
      <title>Software Intern</title>
      <responsibilities>
        <bullet>First supported employment bullet.</bullet>
        <bullet>Second supported employment bullet.</bullet>
        <bullet>Third supported employment bullet.</bullet>
      </responsibilities>
    </job>
  </employment>
</resume>
XML

if "$ROOT/bin/validate_resume.sh" "$ONE_JOB_RESUME" >"$ONE_JOB_LOG" 2>&1; then
  echo "Expected single-employment resume validation to fail." >&2
  exit 1
fi

grep -q "at least 2 employment entries" "$ONE_JOB_LOG"

if "$ROOT/bin/run_resume.sh" "$ONE_JOB_RESUME" "$OUT_DIR/one_job_resume.pdf" >"$ONE_JOB_GENERATOR_LOG" 2>&1; then
  echo "Expected resume generation with one employment entry to fail." >&2
  exit 1
fi

test ! -f "$OUT_DIR/one_job_resume.pdf"
grep -q "at least 2 employment entries" "$ONE_JOB_GENERATOR_LOG"

cat > "$BAD_MATRIX" <<'JSON'
{
  "company": "Example Company",
  "role_title": "Software Engineer",
  "role_type": "software_engineer",
  "layout_profile": "unknown_profile",
  "top_keywords": [],
  "top_requirements": [],
  "requirement_to_evidence": [],
  "selected_projects": [],
  "selected_employment": [],
  "selected_skills": [],
  "gaps": [],
  "resume_strategy": "Use relevant software evidence.",
  "cover_letter_strategy": "Use relevant software evidence."
}
JSON

if "$ROOT/bin/validate_match_matrix.sh" "$BAD_MATRIX" >"$MATRIX_LOG" 2>&1; then
  echo "Expected bad match matrix validation to fail." >&2
  exit 1
fi

grep -q "layout_profile" "$MATRIX_LOG"
grep -q "selected_projects" "$MATRIX_LOG"

"$ROOT/bin/validate_cover_letter.sh" "$ROOT/examples/example_cover_letter.txt"
"$ROOT/bin/validate_resume.sh" "$ROOT/examples/example_resume.xml"
"$ROOT/bin/validate_match_matrix.sh" "$ROOT/examples/example_match_matrix.json" --resume-xml "$ROOT/examples/example_resume.xml"

echo "Validator smoke test passed."
echo "Cover validator log:  $COVER_LOG"
echo "Resume validator log: $RESUME_LOG"
